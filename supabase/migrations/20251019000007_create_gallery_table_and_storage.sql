-- Migration: Create gallery table and gallery-photos storage bucket
-- Non-destructive migration: uses if not exists and on conflict

-- 1. Table: public.gallery_items
create table if not exists public.gallery_items (
    id bigint generated by default as identity primary key,
    title text not null check (char_length(trim(title)) > 0 and char_length(title) <= 150),
    category text not null check (category in ('kegiatan', 'hasil')),
    caption text check (caption is null or char_length(caption) <= 500),
    image_url text not null,
    storage_path text not null,
    created_at timestamptz not null default now(),
    created_by uuid references auth.users(id)
);

create index if not exists idx_gallery_items_category on public.gallery_items(category);
create index if not exists idx_gallery_items_created_at on public.gallery_items(created_at desc);

-- 2. Enable RLS
alter table public.gallery_items enable row level security;

-- 3. RLS Policies for public.gallery_items
-- Public can read gallery items (select queries by public fetch safe fields)
create policy "Public can read gallery items"
on public.gallery_items
for select
to anon, authenticated
using (true);

-- Only allowlisted pengurus can insert gallery items
create policy "Only allowlisted pengurus can insert gallery items"
on public.gallery_items
for insert
to authenticated
with check (
    exists (
        select 1 from public.pengurus_allowlist
        where pengurus_allowlist.user_id = auth.uid()
    )
);

-- Only allowlisted pengurus can update gallery items
create policy "Only allowlisted pengurus can update gallery items"
on public.gallery_items
for update
to authenticated
using (
    exists (
        select 1 from public.pengurus_allowlist
        where pengurus_allowlist.user_id = auth.uid()
    )
)
with check (
    exists (
        select 1 from public.pengurus_allowlist
        where pengurus_allowlist.user_id = auth.uid()
    )
);

-- Only allowlisted pengurus can delete gallery items
create policy "Only allowlisted pengurus can delete gallery items"
on public.gallery_items
for delete
to authenticated
using (
    exists (
        select 1 from public.pengurus_allowlist
        where pengurus_allowlist.user_id = auth.uid()
    )
);

-- 4. Storage Bucket: gallery-photos
-- Public bucket for serving photos of kerja bakti and its results to residents
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
    'gallery-photos',
    'gallery-photos',
    true,
    5242880, -- 5MB limit
    array['image/png', 'image/jpeg', 'image/webp']
)
on conflict (id) do update set
    public = true,
    file_size_limit = 5242880,
    allowed_mime_types = array['image/png', 'image/jpeg', 'image/webp'];

-- Storage Policies for gallery-photos
create policy "Public can view gallery photos"
on storage.objects
