-- Migration: Create expenses table, public view, and private receipts storage bucket
-- Non-destructive migration: uses if not exists and on conflict

-- 1. Base Table: public.expenses
-- Base table stores full expense records including private receipts and audit metadata.
create table if not exists public.expenses (
    id bigint generated by default as identity primary key,
    date date not null default current_date,
    description text not null check (char_length(trim(description)) > 0 and char_length(description) <= 255),
    amount bigint not null check (amount > 0),
    receipt_path text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    created_by uuid references auth.users(id),
    updated_by uuid references auth.users(id)
);

create index if not exists idx_expenses_date on public.expenses(date desc);

-- 2. Enable RLS on base table
alter table public.expenses enable row level security;

-- 3. Base Table RLS: Strictly pengurus-only for SELECT, INSERT, UPDATE, DELETE.
-- Public/anon and non-pengurus cannot query public.expenses directly via DB/API.
drop policy if exists "Public can read expenses" on public.expenses;
drop policy if exists "Only allowlisted pengurus can select expenses" on public.expenses;
create policy "Only allowlisted pengurus can select expenses"
on public.expenses
for select
to authenticated
using (
    exists (
        select 1 from public.pengurus_allowlist
        where pengurus_allowlist.user_id = auth.uid()
    )
);

drop policy if exists "Only allowlisted pengurus can insert expenses" on public.expenses;
create policy "Only allowlisted pengurus can insert expenses"
on public.expenses
for insert
to authenticated
with check (
    exists (
        select 1 from public.pengurus_allowlist
        where pengurus_allowlist.user_id = auth.uid()
    )
);

drop policy if exists "Only allowlisted pengurus can update expenses" on public.expenses;
create policy "Only allowlisted pengurus can update expenses"
on public.expenses
for update
to authenticated
using (
    exists (
        select 1 from public.pengurus_allowlist
        where pengurus_allowlist.user_id = auth.uid()
    )
)
with check (
    exists (
        select 1 from public.pengurus_allowlist
        where pengurus_allowlist.user_id = auth.uid()
    )
);

drop policy if exists "Only allowlisted pengurus can delete expenses" on public.expenses;
create policy "Only allowlisted pengurus can delete expenses"
on public.expenses
for delete
to authenticated
using (
    exists (
        select 1 from public.pengurus_allowlist
        where pengurus_allowlist.user_id = auth.uid()
    )
);

-- 4. Public Secure View: public.public_expenses
-- Exposes ONLY non-sensitive fields (id, date, description, amount).
-- Uses security definer view semantics (security_invoker = false) so anon and authenticated non-pengurus
-- can view the financial public record without exposing receipt_path or audit IDs.
create or replace view public.public_expenses
with (security_invoker = false)
as select
    id,
    date,
    description,
    amount
from public.expenses;

-- Grants for public view and base table:
-- Anon & authenticated can select from public_expenses view.
-- Base table public.expenses select grant is restricted to authenticated pengurus via RLS.
grant select on public.public_expenses to anon, authenticated;

-- 5. Supabase Storage: Private Bucket for Expense Receipts
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
    'expense-receipts',
    'expense-receipts',
    false, -- PRIVATE BUCKET: receipts are strictly pengurus-only
    2097152, -- 2MB max
    array['image/png', 'image/jpeg', 'image/webp']
)
on conflict (id) do update set
    public = false,
    file_size_limit = 2097152,
    allowed_mime_types = array['image/png', 'image/jpeg', 'image/webp'];

-- Storage policies: STRICTLY allowlisted pengurus only (No public/anon access)
