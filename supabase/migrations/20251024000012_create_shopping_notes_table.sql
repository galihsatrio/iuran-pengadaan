-- Migration: Create shopping_notes and shopping_note_items tables, plus shopping-note-photos private storage bucket

-- 1. Base Table: public.shopping_notes
create table if not exists public.shopping_notes (
    id bigint generated by default as identity primary key,
    title text not null check (char_length(trim(title)) > 0 and char_length(title) <= 100),
    date date not null default current_date,
    photo_path text,
    total_amount bigint not null check (total_amount >= 0),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    created_by uuid references auth.users(id),
    updated_by uuid references auth.users(id)
);

create index if not exists idx_shopping_notes_date on public.shopping_notes(date desc);

-- 2. Detail Table: public.shopping_note_items
create table if not exists public.shopping_note_items (
    id bigint generated by default as identity primary key,
    note_id bigint not null references public.shopping_notes(id) on delete cascade,
    item_name text not null check (char_length(trim(item_name)) > 0 and char_length(item_name) <= 200),
    item_price bigint not null check (item_price >= 0),
    sort_order int not null default 0
);

create index if not exists idx_shopping_note_items_note_id on public.shopping_note_items(note_id);

-- 3. Enable RLS
alter table public.shopping_notes enable row level security;
alter table public.shopping_note_items enable row level security;

