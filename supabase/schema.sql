-- Public Secure View: public_expenses
-- Exposes ONLY non-sensitive financial fields (id, date, description, amount).
create or replace view public.public_expenses
with (security_invoker = false)
as select
    id,
    date,
    description,
    amount,
    procurement_group
from public.expenses;

grant select on public.public_expenses to anon, authenticated;

