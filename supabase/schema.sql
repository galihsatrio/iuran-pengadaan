-- Skema Database dan Row Level Security (RLS)
-- Iuran Pengadaan Portal Warga

-- 1. Tabel Daftar Izin Pengurus (Allowlist)
-- Menampung user_id dari auth.users yang berhak membuat pencatatan iuran.
create table if not exists public.pengurus_allowlist (
    user_id uuid primary key references auth.users(id) on delete cascade,
    email text not null,
    created_at timestamptz not null default now()
);

-- 2. Tabel Pencatatan Iuran
create table if not exists public.iuran (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    nama_blok text not null check (char_length(trim(nama_blok)) > 0 and char_length(nama_blok) <= 50),
    nomor_blok text not null check (char_length(trim(nomor_blok)) > 0 and char_length(nomor_blok) <= 20),
    nama_kepala_keluarga text not null check (char_length(trim(nama_kepala_keluarga)) > 0 and char_length(nama_kepala_keluarga) <= 100),
    amount bigint not null check (amount > 0),
    created_by uuid references auth.users(id) default auth.uid()
);

-- 3. Aktifkan Row Level Security (RLS)
alter table public.pengurus_allowlist enable row level security;
alter table public.iuran enable row level security;

-- 4. Kebijakan RLS untuk pengurus_allowlist
-- Pengguna terautentikasi dapat mengecek status allowlist miliknya sendiri
create policy "Allow user to check own allowlist status"
on public.pengurus_allowlist
for select
to authenticated
using (user_id = auth.uid());

-- 5. Kebijakan RLS untuk iuran
-- Publik / Warga (anon & authenticated) hanya bisa membaca (SELECT) rekap iuran
create policy "Public warga can read iuran"
on public.iuran
for select
to anon, authenticated
using (true);

-- Hanya pengurus yang terdaftar di pengurus_allowlist yang boleh menambah iuran (INSERT)
-- PENTING: Bukan sembarang authenticated user!
create policy "Only allowlisted pengurus can insert iuran"
on public.iuran
for insert
to authenticated
with check (
    created_by = auth.uid()
    and exists (
        select 1 from public.pengurus_allowlist
        where pengurus_allowlist.user_id = auth.uid()
    )
);

-- Pengurus allowlist dapat memperbarui data iuran (UPDATE)
create policy "Only allowlisted pengurus can update iuran"
on public.iuran
for update
to authenticated
using (
    exists (
        select 1 from public.pengurus_allowlist
        where pengurus_allowlist.user_id = auth.uid()
    )
)
with check (
    exists (
        select 1 from public.pengurus_allowlist
        where pengurus_allowlist.user_id = auth.uid()
    )
);

-- Pengurus allowlist dapat menghapus data iuran (DELETE)
create policy "Only allowlisted pengurus can delete iuran"
on public.iuran
for delete
to authenticated
using (
    exists (
        select 1 from public.pengurus_allowlist
        where pengurus_allowlist.user_id = auth.uid()
    )
);

